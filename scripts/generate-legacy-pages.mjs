import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const entries = {
  home: ['index.html', 'home'],
  catalogue: ['catalogue.html', 'catalogue'],
  product: ['product.html', 'product'],
  conseil: ['conseil.html', 'conseil'],
  contact: ['contact.html', 'contact'],
  'a-propos': ['a-propos.html', 'a-propos'],
  livraison: ['livraison.html', 'livraison'],
  retours: ['retours.html', 'retours'],
  confidentialite: ['confidentialite.html', 'confidentialite'],
  credits: ['credits.html', 'credits'],
  admin: ['admin.html', 'admin'],
};
const pages = Object.fromEntries(
  Object.entries(entries).map(([key, [file, page]]) => {
    const source = readFileSync(file, 'utf8');
    const body = source.match(/<body\b[^>]*>([\s\S]*?)<\/body>/i)?.[1];
    if (!body) throw new Error(`Could not extract body from ${file}`);
    const html = body
      .replace(/<!-- layout:(header|footer|dialogs) -->/g, '')
      .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '');
    return [key, { page, html }];
  }),
);
const destination = resolve('src/generated/legacy-pages.ts');
mkdirSync(dirname(destination), { recursive: true });
writeFileSync(
  destination,
  `// Generated by scripts/generate-legacy-pages.mjs; do not edit.\nexport const legacyPages = ${JSON.stringify(pages)} as const;\n`,
);
